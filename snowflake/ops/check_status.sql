/* Everything you want to look at after pushing a wave. */
USE ROLE S2C_ADMIN;
USE WAREHOUSE S2C_WH;

-- 1. one-glance health
SELECT * FROM S2C_DEV.AUDIT.V_PIPELINE_HEALTH;

-- 2. did every pushed file load? (newest first)
SELECT REPO_PATH, COMMIT_SHA, DATA_ROW_COUNT, LOAD_STATUS, LOADED_ROWS, LOADED_BY, SECONDS_TO_LOAD
FROM S2C_DEV.AUDIT.V_FILE_LINEAGE
ORDER BY REGISTERED_AT DESC
LIMIT 50;

-- 3. pre-load checks done by the uploader
SELECT * FROM S2C_DEV.AUDIT.PRELOAD_CHECK_LOG WHERE STATUS <> 'PASS' ORDER BY CHECKED_AT DESC;

-- 4. latest DQ results, failing rules first
SELECT * FROM S2C_DEV.AUDIT.V_DQ_LATEST_RESULTS ORDER BY STATUS, SEVERITY, RULE_ID;

-- 5. gate for dbt
SELECT * FROM S2C_DEV.AUDIT.V_PIPELINE_GATE;

-- 6. speed layer
SELECT * FROM S2C_DEV.STREAMING.RISK_ALERTS ORDER BY CREATED_AT DESC LIMIT 20;
SELECT REJECT_REASON, COUNT(*) FROM S2C_DEV.STREAMING.RISK_DEAD_LETTER GROUP BY 1;
SELECT * FROM S2C_DEV.STREAMING.RISK_CURRENT ORDER BY UPDATED_AT DESC LIMIT 20;

-- 7. task history (last 2 hours)
SELECT NAME, STATE, SCHEDULED_TIME, COMPLETED_TIME, RETURN_VALUE, ERROR_MESSAGE
FROM TABLE(S2C_DEV.INFORMATION_SCHEMA.TASK_HISTORY(
       SCHEDULED_TIME_RANGE_START => DATEADD(HOUR, -2, CURRENT_TIMESTAMP())))
ORDER BY SCHEDULED_TIME DESC;

-- 8. Snowpipe status
SELECT SYSTEM$PIPE_STATUS('S2C_DEV.RAW.PIPE_RISK_EVENTS');
