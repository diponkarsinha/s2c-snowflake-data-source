/* =============================================================================
   10_monitoring_views.sql
   -----------------------------------------------------------------------------
   V_PIPELINE_GATE        one row: PASS / BLOCKED. dbt checks this before
                          building Gold (open, unacknowledged blocking issues).
   V_DQ_OPEN_FAILURES     failing records seen in the latest DQ run
   V_ROW_DQ_STATUS        worst open severity per RAW row -> used by dbt to
                          quarantine rows (join on _FILE_NAME + _FILE_ROW_NUMBER)
   V_DQ_LATEST_RESULTS    rule-by-rule result of the latest run
   V_FILE_LINEAGE         every file: Git path, commit, checksum, load status
   V_PIPELINE_HEALTH      one-glance health of tasks, pipe, loads and stream
   V_ISSUES_TODAY         what went wrong today, grouped by rule
   ============================================================================= */

USE ROLE S2C_ADMIN;
USE DATABASE S2C_DEV;
USE SCHEMA AUDIT;

CREATE OR REPLACE VIEW S2C_DEV.AUDIT.V_LATEST_DQ_RUN AS
SELECT *
FROM S2C_DEV.AUDIT.DQ_RUN_LOG
WHERE STATUS IN ('SUCCESS', 'PARTIAL')
QUALIFY ROW_NUMBER() OVER (ORDER BY STARTED_AT DESC) = 1;

CREATE OR REPLACE VIEW S2C_DEV.AUDIT.V_DQ_OPEN_FAILURES AS
SELECT f.*
FROM S2C_DEV.AUDIT.DQ_FAILED_RECORDS f
JOIN S2C_DEV.AUDIT.V_LATEST_DQ_RUN r ON f.LAST_SEEN_RUN_ID = r.RUN_ID
WHERE NOT f.ACKNOWLEDGED;

CREATE OR REPLACE VIEW S2C_DEV.AUDIT.V_PIPELINE_GATE AS
SELECT
    (SELECT COUNT(*) FROM S2C_DEV.AUDIT.V_DQ_OPEN_FAILURES WHERE IS_BLOCKING) AS OPEN_BLOCKING_ISSUES,
    IFF(OPEN_BLOCKING_ISSUES = 0, 'PASS', 'BLOCKED')                          AS GATE_STATUS,
    (SELECT MAX(FINISHED_AT) FROM S2C_DEV.AUDIT.V_LATEST_DQ_RUN)              AS LAST_DQ_RUN_AT,
    DATEDIFF(MINUTE, LAST_DQ_RUN_AT, CURRENT_TIMESTAMP())                     AS MINUTES_SINCE_DQ_RUN;

CREATE OR REPLACE VIEW S2C_DEV.AUDIT.V_ROW_DQ_STATUS AS
SELECT
    RAW_TABLE,
    FILE_NAME,
    FILE_ROW_NUMBER,
    MAX(CASE SEVERITY WHEN 'ERROR' THEN 3 WHEN 'WARN' THEN 2 ELSE 1 END)   AS SEVERITY_RANK,
    CASE MAX(CASE SEVERITY WHEN 'ERROR' THEN 3 WHEN 'WARN' THEN 2 ELSE 1 END)
         WHEN 3 THEN 'ERROR' WHEN 2 THEN 'WARN' ELSE 'INFO' END             AS DQ_STATUS,
    ARRAY_AGG(DISTINCT RULE_ID)                                           AS RULE_IDS
FROM S2C_DEV.AUDIT.V_DQ_OPEN_FAILURES
WHERE FILE_ROW_NUMBER IS NOT NULL
GROUP BY RAW_TABLE, FILE_NAME, FILE_ROW_NUMBER;

CREATE OR REPLACE VIEW S2C_DEV.AUDIT.V_DQ_LATEST_RESULTS AS
SELECT r.RULE_ID, d.RULE_NAME, d.CHECK_LEVEL, r.SEVERITY, r.IS_BLOCKING, r.STATUS,
       r.FAILED_COUNT, r.NEW_COUNT, r.SAMPLE_KEYS, r.ERROR_MESSAGE, r.CHECKED_AT
FROM S2C_DEV.AUDIT.DQ_RESULTS_LOG r
JOIN S2C_DEV.AUDIT.V_LATEST_DQ_RUN l ON l.RUN_ID = r.RUN_ID
LEFT JOIN S2C_DEV.AUDIT.DQ_RULES d ON d.RULE_ID = r.RULE_ID;

CREATE OR REPLACE VIEW S2C_DEV.AUDIT.V_FILE_LINEAGE AS
SELECT
    r.REGISTRY_ID, r.ENTITY, r.REPO_PATH, r.FILE_NAME, r.COMMIT_SHA, r.PUSHED_BY, r.REGISTERED_AT,
    r.MD5, r.SIZE_BYTES, r.DATA_ROW_COUNT, r.EXPECTED_RAW_ROWS,
    r.STAGE_NAME, r.STAGE_PATH,
    l.RAW_TABLE, l.STATUS AS LOAD_STATUS, l.ROW_COUNT AS LOADED_ROWS, l.ERROR_COUNT,
    l.PIPE_NAME, l.LAST_LOAD_TIME,
    IFF(l.PIPE_NAME IS NOT NULL, 'SNOWPIPE', IFF(l.RAW_TABLE IS NOT NULL, 'COPY', NULL)) AS LOADED_BY,
    DATEDIFF(SECOND, r.REGISTERED_AT, l.LAST_LOAD_TIME) AS SECONDS_TO_LOAD
FROM S2C_DEV.AUDIT.FILE_REGISTRY r
LEFT JOIN S2C_DEV.AUDIT.FILE_LOAD_LOG l
  ON ENDSWITH(l.FILE_NAME, r.STAGE_PATH) OR l.FILE_NAME = r.STAGE_PATH;

CREATE OR REPLACE VIEW S2C_DEV.AUDIT.V_ISSUES_TODAY AS
SELECT f.RULE_ID, d.RULE_NAME, f.SEVERITY, f.IS_BLOCKING,
       COUNT(*) AS RECORDS, MIN(f.FIRST_SEEN_AT) AS FIRST_SEEN, ARRAY_AGG(DISTINCT f.RECORD_KEY) AS KEYS
FROM S2C_DEV.AUDIT.DQ_FAILED_RECORDS f
LEFT JOIN S2C_DEV.AUDIT.DQ_RULES d ON d.RULE_ID = f.RULE_ID
WHERE f.FIRST_SEEN_AT >= CURRENT_DATE()
GROUP BY f.RULE_ID, d.RULE_NAME, f.SEVERITY, f.IS_BLOCKING;

CREATE OR REPLACE VIEW S2C_DEV.AUDIT.V_PIPELINE_HEALTH AS
SELECT 'Last batch load run'  AS CHECK_NAME,
       (SELECT TO_VARCHAR(MAX(STARTED_AT), 'YYYY-MM-DD HH24:MI') || ' - ' || ANY_VALUE(STATUS)
          FROM (SELECT * FROM S2C_DEV.AUDIT.LOAD_RUN_LOG QUALIFY ROW_NUMBER() OVER (ORDER BY STARTED_AT DESC) = 1)) AS VALUE
UNION ALL
SELECT 'Last DQ run',
       (SELECT TO_VARCHAR(STARTED_AT, 'YYYY-MM-DD HH24:MI') || ' - ' || STATUS || ', ' || RULES_FAILED || ' rules failing'
          FROM S2C_DEV.AUDIT.V_LATEST_DQ_RUN)
UNION ALL
SELECT 'Gate', (SELECT GATE_STATUS || ' (' || OPEN_BLOCKING_ISSUES || ' blocking issues)' FROM S2C_DEV.AUDIT.V_PIPELINE_GATE)
UNION ALL
SELECT 'Snowpipe state', PARSE_JSON(SYSTEM$PIPE_STATUS('S2C_DEV.RAW.PIPE_RISK_EVENTS')):executionState::STRING
UNION ALL
SELECT 'Last risk event loaded', (SELECT TO_VARCHAR(MAX(_LOADED_AT), 'YYYY-MM-DD HH24:MI') FROM S2C_DEV.RAW.RISK_EVENTS)
UNION ALL
SELECT 'Open risk alerts', (SELECT COUNT(*)::VARCHAR FROM S2C_DEV.STREAMING.RISK_ALERTS WHERE STATUS = 'OPEN')
UNION ALL
SELECT 'Dead-letter events', (SELECT COUNT(*)::VARCHAR FROM S2C_DEV.STREAMING.RISK_DEAD_LETTER)
UNION ALL
SELECT 'Files registered / loaded',
       (SELECT COUNT(*) || ' / ' || COUNT(LOAD_STATUS) FROM S2C_DEV.AUDIT.V_FILE_LINEAGE);

GRANT SELECT ON ALL VIEWS IN SCHEMA S2C_DEV.AUDIT TO ROLE S2C_TRANSFORMER;
